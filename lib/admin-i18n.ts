/**
 * ===========================================================================
 * AFNON — every word the STAFF read in the admin panel, in Uzbek, Russian
 * and English.
 * ===========================================================================
 * · This is the panel's own interface: tabs, buttons, hints, confirmations,
 *   toasts. It is a separate thing from the per-language CONTENT fields (dish
 *   names, category labels, About us) that staff type in — those live in the
 *   database and are not translated here.
 * · Uzbek is the default: the people standing in the restaurant read it.
 * · The English dictionary defines the shape; TypeScript refuses to build if
 *   Uzbek or Russian is missing a key.
 * · The language is remembered in its own cookie, separate from the visitor's,
 *   so a member of staff previewing the site in Russian does not flip the
 *   panel with it.
 * ===========================================================================
 */

